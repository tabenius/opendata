/** Writes apps/pwa/public/_headers (Cloudflare static assets) from the API's header policy. */
import { writeFileSync } from "node:fs";
import { HTML_CSP, SECURITY_HEADERS } from "../apps/api/src/app";

export function headersFile(): string {
  const common = Object.entries(SECURITY_HEADERS).map(([k, v]) => `  ${k}: ${v}`);
  return ["# Generated by scripts/gen-headers.ts from apps/api/src/app.ts. Do not edit.", "/*", ...common, `  Content-Security-Policy: ${HTML_CSP}`, ""].join("\n");
}

if (process.argv[1]?.endsWith("gen-headers.ts")) {
  writeFileSync(new URL("../apps/pwa/public/_headers", import.meta.url), headersFile());
  console.log("wrote apps/pwa/public/_headers");
}
